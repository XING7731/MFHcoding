#ifndef __MQ2_H
#define __MQ2_H

#include "stm32f1xx_hal.h"

/* ============================ 单位说明 ============================
 * MQ-2 输出为模拟电压, 半导体气敏元件的电压-浓度关系需要针对具体器件
 * 在标准气体下标定, 才能换算成 ppm 之类的物理浓度。
 * 本固件不做 ppm 换算, 输出定义为:
 *
 *     gas_level = ADC原始值 × 100 / 4095     (0 ~ 100, 相对量程百分数)
 *
 * 即"满量程的相对比例", 不是 ppm, 也不是 LEL。需求给出的报警阈值 50
 * 相应地解释为"ADC 量程的 50%"。若需 ppm, 必须自行标定并替换换算函数。
 *
 * 预热: MQ-2 需要预热后读数才稳定(具体时间见其数据手册), 预热期内
 * 返回值标记为无效(gas_ok = 0), 不参与报警判断。
 * ================================================================= */
void     MQ2_Init(ADC_HandleTypeDef *hadc);
uint8_t  MQ2_Read(uint16_t *level_0_100);   /* 0 = 成功且已过预热期 */

#endif /* __MQ2_H */
