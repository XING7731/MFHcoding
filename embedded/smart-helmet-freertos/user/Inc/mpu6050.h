#ifndef __MPU6050_H
#define __MPU6050_H

#include "stm32f1xx_hal.h"

/* 说明: 本驱动只读取原始加速度/角速度寄存器, 不使用 MPU6050 内部 DMP。
 * 原因: DMP 需移植 InvenSense 官方运动驱动库(体积与 RAM 占用对
 *       STM32F103C8T6 的 64KB Flash / 20KB RAM 不划算), 且代码可验证性差。
 *       摔倒检测直接基于加速度模值判断, 数据来源透明、便于论文复现。
 *
 * 加速度量程由 MPU6050_ACCEL_FS_G 决定(见 user_config.h), 必须 > 报警阈值,
 * 否则冲击会被量程削顶而无法识别。
 *
 * ---------------------------------------------------------------------------
 * 【量程自检 —— 本驱动不再"假设"量程写进去了】
 *
 * 为什么必须读回核对:
 *   量产 MPU6050 / 克隆片(GY-521 模块上很常见)偶发 ACCEL_CONFIG 写入不生效,
 *   芯片停在寄存器复位的 ±2g 默认档。此时若代码仍按配置的 ±8g(4096 LSB/g)
 *   换算, 读数会被整体放大 4 倍 —— 静止时本该 1.0g 的合加速度会显示成 ~4g。
 *
 *   后果不是"数值不准"这么轻。摔倒判据是状态机:
 *     ① |a| > FALL_ACCEL_HIGH_G   ② 100ms 内再次超阈
 *     ③ 随后 1.5s 内持续 < FALL_ACCEL_LOW_G
 *   偏置把 |a| 常年顶在 4g, 条件③永不满足 → 真摔也不报警, 而屏幕上
 *   一切正常(st=normal)。这是最难发现的一类失效: 功能没了, 却没有任何提示。
 *
 *   【2026-09-16 补充: 实测遇到的是更隐蔽的一种】
 *   手上这颗克隆片连"读回校验"都能骗过 —— ACCEL_CONFIG 写 ±8g 后读回
 *   也是 ±8g(自检屏显示 "8g->8g OK"), 但内部灵敏度仍锁在 ±2g 的
 *   16384 LSB/g。此时 fs_match=1、fatal=0, 屏幕全绿, 读数却整体放大 4 倍。
 *   这种片子只能靠"静止时 |a| 应该 ≈1g"这个物理常识识破, 详见
 *   docs/25-摔倒阈值调整与克隆片读数放大.md。
 *
 *   【2026-09-16 第二版: 不再靠"调阈值迁就错误读数", 而是把读数修对】
 *   上一版的应对是把判定阈值一并放大到同一读数体系(2.5→5.0, 1.5→4.5)。
 *   那是权宜之计, 代价有三:
 *     ① 阈值从此不对应需求文档里的物理值, 验收/复现时无法自圆其说;
 *     ② 稳定窗口被压成 5.0~4.5 这 0.5g 的窄带, 摔后稍有晃动就反复重置计时;
 *     ③ 参数绑死在"这一批片子的错误"上 —— 换一片量程正常的芯片, 同一个
 *        固件读数就又不准了。
 *
 *   本版改用【静止自标定】把读数直接修对。所依据的物理事实只有一条:
 *
 *        静止时重力矢量长度恒为 1g  →  |a| ≡ 1g, 与姿态无关。
 *
 *   于是: 把静止期间【原始码值】的模值求平均, 得到的数就是真实的 LSB/g
 *   (因为 码值模值 / 真实LSB/g = 1g, 所以 真实LSB/g = 码值模值)。
 *
 *   这一步【完全不依赖任何寄存器读回】: 芯片把 ACCEL_CONFIG 伪造成 ±8g
 *   也没用, 因为"静止时模值对应 1g"是物理定律, 不是寄存器里的一个位。
 *   这也正是本方案与读写回校验的本质区别 ——
 *       读写回校验查的是: "寄存器说的, 和写进去的一致吗?"
 *       静止自标定查的是: "读数和物理定律一致吗?"
 *   克隆片能骗过前者, 骗不过后者。
 *
 *   【顺带澄清一个常见疑问: 它测的到底是加速度还是位置?】
 *   这条判据本身就是答案。位置量在任何姿态下都不可能恒定给出同一个模值,
 *   而加速度计因始终叠着 1g 重力, 模值天然恒定(静止 1g / 失重→0 / 撞击数 g)。
 *   反过来说, 也正因为模值恒定, 摔倒判据用 |a| 才有意义。
 *
 *   【标定失败怎么办】
 *   上电时若帽子正被拿着晃动, "静止"前提不成立, 此时算出的均值没有物理
 *   意义 —— 必须整轮丢弃重来(最多 MPU6050_CAL_RETRY_MAX 轮, 轮间留出放手
 *   时间)。全部失败则回退到寄存器读回推算值(即上一版行为), 并把 cal_ok
 *   置 0 → 屏幕显示 ! ACAL FAIL。宁可明确报"标定没做成", 也不假装读数是对的。
 *
 * 因此 MPU6050_Init() 的做法是:
 *   1) 写完 ACCEL_CONFIG 立刻读回, 不一致则重试(最多 MPU6050_WRITE_RETRY_MAX 次);
 *   2) 灵敏度系数【按实际读回值】换算, 而不是按编译期配置 —— 无论芯片最终
 *      落在哪一档, 报出来的 g 值都是对的;
 *   3) 把 want/got/match 留在 MPU6050_SelfCheck_t 里, 供上电自检屏、
 *      USART2 日志与运行时告警显示。
 *
 * 【为什么不能自动"修好"】
 *   若实际量程 ≤ 摔倒阈值(2g 档 ≤ 2.5g), 冲击被削顶在 2g, 判据在物理上就
 *   不可能触发 —— 这靠软件改不了。此时固件只做一件事: 让它显眼
 *   (SelfCheck.fatal = 1 → 运行时屏幕告警)。降阈值属于检测策略变更, 由人决定,
 *   固件不擅自改。
 *
 * ---------------------------------------------------------------------------
 * 【2026-09-16 第三版: 阈值对了、读数也对了, 为什么还是"怎么扔都不报警"?】
 *
 * 因为问题不在数值, 在【时间】。前面两版一直在修"数得多准", 而摔倒判据真正
 * 依赖的是"看得多勤"和"看得多真"——这两件事当时都是坏的:
 *
 *   ① 采样: Sensor_Task 周期 100ms ⇒ 加速度 10Hz。撞击只持续 5~20ms,
 *      落在两次采样之间的概率 >80%, 信号根本没被看到。而且判据条件2 是
 *      "100ms 内两次超阈", 采样周期就等于窗口宽度, 该条件几乎不可满足。
 *   ② 带宽: DLPF 配的 44Hz, 对 100Hz 量级的撞击尖峰衰减约 -14dB,
 *      2.0g 的撞击被滤成 0.4g ——【采样再快也超不过 1.8g 阈值】。
 *   ③ 标定时机: 上电自标定要求"上电瞬间静止"。现场是拿着就上电,
 *      标定失败 → 读数仍被放大 4 倍(静止 3.9) → 阈值 1.8/1.5 全部失效。
 *      ⇒ 本版加【静默期在线标定】, 运行中放稳一两秒即自动修回, 无需重启。
 *
 * 三条合起来的结论: 排查"检测功能不工作"时, 不要只盯着阈值和换算 ——
 *   先问"信号有没有被采到"(采样率 vs 事件持续时间),
 *   再问"采到的还算数吗"(带宽/滤波 vs 事件频率成分),
 *   最后才问"判得对不对"(阈值/状态机)。
 * 这三问的顺序, 就是本文件三次修订的先后顺序。
 * ---------------------------------------------------------------------------
 */

/* 加速度量程写入的重试次数。取 3: 克隆片多为"第一次写不进、第二次就好",
 * 3 次足以覆盖, 又不会让上电多等太久(每次仅隔 2ms)。 */
#define MPU6050_WRITE_RETRY_MAX   3

/* ---------------- 静止自标定参数(依据"静止时 |a| ≡ 1g") ----------------
 * 采样点数 × 间隔 = 单轮标定时长。64 点 × 3ms ≈ 190ms —— 短到用户松手后
 * 不会等太久, 长到足以跨过几次传感器内部采样, 避开单点噪声。
 * 间隔取 3ms 而不是更小: 100Hz 采样率下芯片每 10ms 才更新一次数据, 采太快
 * 只会重复读到同一个样本, 反而低估真实抖动。 */
#define MPU6050_CAL_SAMPLES       64     /* 单轮采样点数 */
#define MPU6050_CAL_INTERVAL_MS   3      /* 采样间隔(ms) */
#define MPU6050_CAL_RETRY_MAX     4      /* 静止判定失败时整轮重试上限 */
#define MPU6050_CAL_RETRY_GAP_MS  250    /* 轮间等待, 留给"手离开帽子" */

/* "静止"判据: 模值极差占均值的百分比上限。
 * 取 6% —— 手扶着一般的桌面振动约 1~3%, 戴着帽子呼吸起伏约 5%, 取 6 能
 * 通过"放着但没完全静止"的常见情形, 又能拦住明显的晃动(通常 >15%)。 */
#define MPU6050_CAL_SPREAD_PCT    6.0f

/* 标定结果的物理合理区间(LSB/g)。
 * 下界 500: 低于 ±16g 档(2048)还有 4 倍余量, 再小说明根本不是加速度计的数据;
 * 上界 40000: 高于 ±2g 档(16384)还有 2.4 倍余量, 再大说明模值被异常放大。
 * 落在区间外一律判标定失败并回退 —— 与其相信一个离奇的数, 不如如实报错。 */
#define MPU6050_CAL_MIN_LSB       500.0f
#define MPU6050_CAL_MAX_LSB       40000.0f

typedef struct
{
    float ax, ay, az;   /* g */
    float gx, gy, gz;   /* °/s (按量程换算, 未做零偏/温度标定) */

    /* 三轴加速度的【原始码值】, 与上面 ax/ay/az 同源(同一帧 I2C 读出)。
     * 2026-09-16 新增, 用途只有一个: 供静默期在线标定使用。
     * 标定必须拿原始码值 —— 用换算过的值去修换算系数是循环论证。 */
    int16_t raw_ax, raw_ay, raw_az;
} MPU6050_Data_t;

/* 量程自检结果 —— 由 MPU6050_Init() 填写, 之后只读。 */
typedef struct
{
    uint8_t init_rc;        /* MPU6050_Init() 返回码: 0=正常 1=I2C读失败 2=WHO_AM_I不符 */
    uint8_t who_am_i;       /* 实际读到的 WHO_AM_I(0x75), 正常应为 0x68 */
    uint8_t accel_cfg_wr;   /* 期望写入 ACCEL_CONFIG(0x1C) 的值 */
    uint8_t accel_cfg_rd;   /* 实际读回 ACCEL_CONFIG 的值 */
    uint8_t fs_want;        /* 配置期望的量程(g): 2/4/8/16 */
    uint8_t fs_got;         /* 由读回值解出的实际量程(g); 0=没能读到 */
    uint8_t fs_match;       /* 1 = 读回值与写入值一致(量程按预期生效) */
    uint8_t retry;          /* 写入重试次数: 0 = 一次就成 */

    /* ---- 静止自标定结果(2026-09-16 新增) ----
     * 依据"静止时 |a| ≡ 1g"反推真实灵敏度, 全程不看寄存器读回。
     * 这就是"实测遇到的克隆片把读回也伪造了"的最终解法。 */
    uint8_t cal_ok;         /* 1 = 自标定成功, 换算已改用实测灵敏度 */
    uint8_t cal_retry;      /* 在第几轮静止判定中通过(0 = 首轮即过) */
    uint8_t fs_cal;         /* 由实测灵敏度反推的量程(g): 2/4/8/16; 0 = 未标定 */
    float   cal_lsb;        /* 实测灵敏度 LSB/g(静止原始码值模值的均值) */
    float   cal_mean_raw;   /* 标定期间原始模值均值(码值), 与 cal_lsb 同源 */
    float   cal_spread_pct; /* 标定期间模值极差占均值的百分比, 越小越静止 */
    float   reg_lsb;        /* 寄存器读回推算的灵敏度 LSB/g, 供对照 */

    uint8_t fs_used;        /* fatal 判据实际采用的量程估计(标定值优先) */
    uint8_t fatal;          /* 1 = 实际量程 ≤ 摔倒阈值, 冲击削顶, 判据永远无法触发 */

    /* ---- 静默期在线标定结果(2026-09-16 新增) ----
     * 上电那一轮标定若因"上电时正在动"而失败, 靠这组值在运行中自行修回来,
     * 不必重启、也不必专门配合。 */
    uint8_t online_ok;      /* 已成功修正的次数(>0 即说明读数已可信) */
    float   online_lsb;     /* 最近一次在线修正得到的灵敏度 LSB/g */
    float   online_spread;  /* 该窗口的极差百分比(越小越静止) */
} MPU6050_SelfCheck_t;

uint8_t MPU6050_Init(I2C_HandleTypeDef *hi2c);
uint8_t MPU6050_Read(MPU6050_Data_t *d);   /* 0 = 成功 */

/* 量程自检结果(只读)。未初始化时各字段为 0, 可安全调用。 */
const MPU6050_SelfCheck_t *MPU6050_GetSelfCheck(void);

/* 当前实际生效的加速度量程(g), 由寄存器读回值解出。供运行时与配置比对。
 * 注意: 克隆片可能把这个值也伪造成配置值, 所以它只说明"寄存器怎么说的";
 * "芯片实际在哪个档"要看 MPU6050_GetSelfCheck()->fs_cal(物理实测反推)。 */
uint8_t MPU6050_GetAccelFsG(void);

/* 当前用于把原始码值换算成 g 的灵敏度(LSB/g)。
 * 标定成功时 = 实测值; 失败时 = 寄存器读回推算值。
 * 现场自查: 静止时 |a| 应 ≈ 1.0g, 不等于 1.0 就说明这个系数不对。 */
float MPU6050_GetAccelLsbPerG(void);

/* 1 = 静止自标定成功(读数是真实 g); 0 = 未标定, 读数按寄存器读回换算。 */
uint8_t MPU6050_IsCalibrated(void);

/* 静默期在线标定 —— 由撞击监视任务每采到一个样本调用一次。
 *
 * 传入【原始码值】(即 MPU6050_Data_t 的 raw_ax/raw_ay/raw_az)。
 * 内部按 MPU6050_ONLINE_CAL_WIN_MS 为窗口累计极差与均值, 窗口结束且满足
 * "够静止 + 数值在物理合理区间"时, 就地修正换算系数。
 *
 * 【为什么需要它】上电自标定只在"上电那一瞬间静止"时成立; 现场更常见的是
 * 拿着就上电了 —— 那样标定失败、读数仍被放大, 判据静默失效。在线标定让
 * 设备在运行中自己修回来(放稳一两秒即可), 不需要重启或专门配合。
 *
 * 开销: 每次只做几次浮点加减, 无数组、无内存分配。 */
void MPU6050_OnlineCalFeed(int16_t raw_ax, int16_t raw_ay, int16_t raw_az);

/* 1 = 当前读数是可信的真实 g(上电标定成功, 或在线标定已修正过至少一次)。
 * 显示屏用它决定是否还要挂 ! ACAL FAIL 告警。 */
uint8_t MPU6050_IsScaleTrusted(void);

#endif /* __MPU6050_H */
