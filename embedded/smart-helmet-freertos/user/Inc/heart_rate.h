#ifndef __HEART_RATE_H
#define __HEART_RATE_H

#include "stm32f1xx_hal.h"

/* ============================================================================
 * PPG 心率/血氧处理 (简化算法, 非医疗级, 明确声明其局限)
 *
 * 【2026-09-16 重写】起因: 用户报"心率检测模块不稳定, 读数随机"。
 *   旧版的四个缺陷(数值验证见 tools/ppg_hr_sim.py, 14→19 项断言):
 *     ① 直流估计初值为 0 ⇒ 上电瞬间整个直流(约 50000)被当成交流, 峰值参考
 *        被顶到 18262, 峰阈值 9131, 而脉搏波只有约 600 LSB
 *        ⇒ 【上电后 109 秒内根本测不到峰】。现场表现=“偶尔蹦出个莫名其妙的数”。
 *     ② 寻峰判据"上一拍在阈值上且本拍更低" ⇒ 下降沿每一步都算峰
 *        (40 秒判出 360 个峰, 真实 48 拍) ⇒ 峰位漂移 ⇒ 读数乱跳。
 *     ③ 没有绝对幅度下限 + 有效性永不清零 ⇒ 拿开手指后既编数(60~170bpm)
 *        又一直显示旧值。
 *     ④ FIFO 溢出丢样本不进时间轴 ⇒ IBI 系统性偏短 ⇒ 心率整体偏高
 *        (仿真: 真值 72 被读成 91.7)。
 *
 * 心率(现在的做法):
 *   带通(高通 0.5Hz 去基线漂移 + 低通 4Hz 去噪声)
 *   → 局部极大值寻峰 + 不应期 + 双向自适应阈值 + 绝对幅度下限
 *   → IBI 离群剔除(带"心率真的变了"的逃生通道)
 *   → 在【采集窗口】内累计每拍的 IBI → 窗口结束取中位数 → HR = 60000/IBI
 *   仿真结果(ppg_hr_sim.py): 静止/基线漂移/漂移+噪声三种条件下标准差
 *             ≤ 1.0 bpm; 没手指时报无效; 丢样本不影响结果。
 *   仿真结果(ppg_measure_sim.py): 一次测量流程下的最终值偏差 ≤ 2bpm。
 *
 * 血氧:
 *   计算 R = (AC_red/DC_red) / (AC_ir/DC_ir) —— 纯数据运算, 任何时候都能算。
 *   但 R → SpO2 的换算式含器件/佩戴相关的标定系数, 所以按 SPO2_MODE 分三档
 *   (见 user_config.h): 0 关闭 / 1 未标定估算 / 2 已标定。
 *   默认 MODE=1: 给出估算值让演示能看到数, 同时用 spo2_cal=0 明确标注
 *   "未标定" —— 不标定的数字不能当医学结论用, 这一点必须写在论文里。
 *
 * 已知局限(必须写进论文/报告):
 *   - 手部晃动、佩戴松动、环境强光会造成运动伪影, 心率会明显失真;
 *     本算法只做了固定带通, 没有做运动伪影抑制(那需要加速度计做自适应滤波);
 *   - 一次测量给出的是【这 15 秒的平均心率】(2026-09-22 从 10 秒加长),
 *     不是瞬时心率, 也不反映窗口内心率的变化; 要连续监测心率变化需要另做
 *     (窗口滑动)模式;
 *   - 未做皮肤接触检测(用"IR 原始值 + 直流 + 调制深度"间接近似);
 *   - 血氧未经标定, 只能作为演示数据。
 *
 * 【2026-09-17 新增一: 接触判定 + 贴手后稳定期】
 *   起因: "心率和血氧测量还是会误测"。
 *   前面几版补掉的都是【算法缺陷】, 但"手指刚贴上"那一瞬间的误测不是算法
 *   问题 —— 是物理过程本身没稳: 直流阶跃让高通先冲一个假峰、指尖受压后
 *   血容量在重新分布、手指还在找位置。这三条调阈值都解决不了, 只能等。
 *
 * 【2026-09-17 新增二: 改成"一次测量"】
 *   流程: 贴上 → 稳定 PPG_SETTLE_MS → 采集 PPG_MEASURE_MS → 出最终结果。
 *   四个状态(HR_State_t):
 *     IDLE      没检测到手指            不发布
 *     SETTLING  稳定期 3s, 只预热        不采集、不发布
 *     MEASURING 采集窗口 15s, 屏上 pending  每拍累计 IBI/R, 不发布
 *     DONE      用整段数据算出的最终值    发布并冻结, 直到手指拿开
 *   ⚠ 窗口长度 2026-09-22 由 10s 改为 15s。依据是 tools/ppg_retry_sim.py 的
 *     窗口扫描(两种漂移模型同方向: 10→15 秒 +13/+17 个百分点), 并顺带否掉
 *     了"自适应早退""自动重试""低置信兜底"三条候选改法 —— 理由都写在
 *     user_config.h 的 PPG_MEASURE_MS 注释里, 不要重复推导。
 *
 *   为什么改成有限窗口: 持续测量时屏上的数每 2 秒变一次, 用户没法判断
 *   "这个数稳了没有"; 有限窗口可以用整段的中位数(10~16 拍投票), 一次伪影
 *   拖不走结果; 窗口一到就冻结, 拿开手指就作废 —— "陈旧值"在结构上消失了。
 *   拿开手指(连续 PPG_CONTACT_OFF_MS 无接触) → 整次测量作废回到 IDLE,
 *   下一次贴上重新走一遍, 绝不会把上一次的残余拍数混进来。
 * ========================================================================== */

/* 测量状态。用途是【告诉用户现在能不能信屏上的数】:
 *   IDLE      → 请贴手指(idle 时屏上是 HR:--, 而不是一个残值)
 *   SETTLING  → 正在稳定, 倒计时还剩几秒(此时不应把 -- 当成故障)
 *   MEASURING → 正在采集, 还要 pending 几秒(同样不要当成故障)
 *   DONE      → 结果已出(可能有效, 也可能是"没测到", 见 HR_GetResult 返回值) */
typedef enum
{
    HR_ST_IDLE      = 0,   /* 未检测到手指 */
    HR_ST_SETTLING  = 1,   /* 已接触, 稳定期内(不采集、不发布) */
    HR_ST_MEASURING = 2,   /* 采集窗口内(屏上 pending) */
    HR_ST_DONE      = 3    /* 测量完成, 最终值已冻结 */
} HR_State_t;


void    HR_Init(void);
void    HR_PushSamples(const uint16_t *ir, const uint16_t *red, uint8_t n);

/* FIFO 溢出丢了 lost 个样本时【必须】调一次, 而且要在推入本批新样本之前调。
 * 作用是把虚拟时间轴补回来 —— 算法用"样本序号 × 20ms"当作时间, 丢了样本
 * 却不告诉它, 算出来的 IBI 就会系统性偏短, 心率整体偏高。
 * 什么时候丢: MAX30102_ReadFifo() 返回的 f.lost 不为 0 时。 */
void    HR_NotifyDrop(uint8_t lost);

uint8_t HR_GetResult(uint16_t *bpm, uint16_t *spo2_percent, uint8_t *spo2_valid);
float   HR_GetRatioR(void);      /* 供标定时观察 R 值; DONE 时给的是
                                  * 最终血氧对应的那个 R(标定要记的就是它) */

/* ---- 测量状态与倒计时(2026-09-17) ----
 * HR_GetResult() 只在 DONE 状态下返回有效值: IDLE/SETTLING/MEASURING 期间
 * 心率返回 0、血氧 valid 返回 0 —— 门控做在算法里而不是显示层, 这样
 * 【屏上和上报给云端的是同一个判断】, 不会出现"屏上 pending、云端有数"。
 *
 * 返回值区分两种情况(屏上必须分开显示, 否则用户分不清"还没好"和"测不到"):
 *   1 → 这次测量成功了, 心率/血氧是最终结果
 *   0 → 还没测完(状态不是 DONE), 或者 10 秒里没攒到足够合格拍数
 *       —— 用 HR_GetState() 区分是哪一种。 */
HR_State_t HR_GetState(void);

/* 稳定期剩余毫秒(IDLE/MEASURING/DONE 时返回 0), 供屏上倒计时用 */
uint32_t   HR_GetSettleRemainMs(void);

/* 采集窗口剩余毫秒(只有 MEASURING 时非 0), 屏上 "PPG: pending 7s" 用它 */
uint32_t   HR_GetMeasureRemainMs(void);

/* 窗口内已经攒到多少个【合格】IBI —— pending 期间看它有没有在涨,
 * 就知道这次测量有没有希望; 测量失败后它说明"只攒到几拍"。 */
uint8_t    HR_GetBeats(void);

/* 是否检测到手指(含去抖)。IDLE 就是"没贴上"。 */
uint8_t    HR_IsTouched(void);

/* ---- PPG 原始量(诊断用) ----
 * 【为什么要把这些数暴露出来】
 *   "心率一直是 --" 有几种完全不同的原因, 而屏上原本分不出来:
 *     ① 传感器根本没收着光(LED 没亮 / 手指没盖住光学窗口 / 模块坏)
 *     ② 收着光了, 但没有脉搏波(贴合不好/压力过大), 或算法还没锁定
 *   把下面两个数写在屏上就能一眼分开:
 *     HR_GetIrDc()      红外通道直流分量 —— 反映"收着多少光"
 *                       手指盖住时通常有几万; ≈0 就是压根没光
 *     HR_GetPeakAmp()   峰值参考(交流幅度) —— 反映"脉搏波有多大"
 *                       DC 正常而它低于 PPG_PEAK_MIN_AMP = 有光但没脉搏波
 *   正常工作时不必看, 排查时看。 */
uint16_t HR_GetIrDc(void);
uint16_t HR_GetPeakAmp(void);

/* HR_GetIrDc() 的【未钳位】版本 —— 供上行报文使用。
 *
 * 【2026-09-22 改写: 它原先的理由是错的】
 *   原写法说"CLAMP 在 65535 会把真实直流十几万报成 65535, 判断 ADC 满量程
 *   会被带反"。实际上 PPG 样本在驱动层就是 `(v & 0x03FFFF) >> 2`, 上限本来
 *   就是 65535(见 max30102.c) —— 所以【d 永远不可能超过 65535】,
 *   与这里钳不钳位无关。判"是不是顶到 ADC 上限"要拿 PPG_ADC_SAT_LEVEL 比,
 *   完整推导与代价见 docs/38。 */
uint32_t HR_GetIrDcRaw(void);

/* 信号质量是否达标。
 * 【本版语义变了】旧版 = "有光 + 调制深度足够"; 现在 = "这次测量真的测出了
 * 心率"(见 heart_rate.c 的 finish_measure)。用于【门控报警】: 报警的唯一
 * 目的是提醒"心率不正常", 一个连心率都没测出来的窗口拿什么去报警?
 * IDLE/SETTLING/MEASURING 期间恒返回 0。 */
uint8_t  HR_IsSignalOk(void);

/* 【这次测量有没有测出结果】(DONE 且最终心率有效)。
 * 屏上用它在 "PPG: done" 和 "PPG: no pulse, retry" 之间选 ——
 * 不能借用快照里的 hr_valid: 快照每 100ms 更新一次而屏 500ms 才刷一次,
 * 状态刚跳到 DONE 的那一刻可能读到上一拍的旧值, 于是先闪一下 "no pulse"
 * 再变成结果。这种一闪而过的东西最容易被当成"不稳定"。
 * (语义上它就等于 DONE 状态下的 HR_IsSignalOk; 分开写是为了让调用处读得懂。) */
uint8_t  HR_IsResultValid(void);

/* 累计因 FIFO 溢出丢掉的样本数。非 0 就说明 I2C 读取跟不上器件产出,
 * 这本身就是"心率抖动/偏高"的一个独立来源 —— 看到它就先去查读取节奏。 */
uint32_t HR_GetDroppedSamples(void);

#endif /* __HEART_RATE_H */
