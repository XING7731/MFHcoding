#ifndef __FALL_DETECT_H
#define __FALL_DETECT_H

#include "stm32f1xx_hal.h"

/* ============================================================================
 * 摔倒/撞击检测状态机 (本项目核心功能)
 *
 * 判据完全按需求实现, 不做自由发挥:
 *   条件1: 加速度模值 |a| > FALL_ACCEL_HIGH_G
 *   条件2: 满足条件1后 FALL_WINDOW_MS(100ms) 内 再次出现 |a| > HIGH_G
 *   条件3: 随后 |a| 持续 FALL_STABLE_MS(1500ms) 落在稳定带
 *          [FALL_STABLE_MIN_G, FALL_ACCEL_LOW_G) 内
 *   三条同时满足 → 判定摔倒, 触发报警
 *
 * ⚠ 条件3 的"稳定带"有下沿(2026-09-16 补):
 *   原来只写 "|a| < 1.5g", 而自由落体中的 |a| ≈ 0g 也小于 1.5g —— "掉到一半
 *   擦到桌沿又接着掉"会被误判成"躺稳了"。加上 0.8g 下沿后, 只有"被支撑着
 *   且不动"的那一段(|a| ≈ 1.0g)才计时。详见 user_config.h 的 FALL_STABLE_MIN_G。
 *
 * ⚠ 阈值与需求原值的关系(2026-09-16 第二次修订):
 *     需求原值: HIGH=2.5g / LOW=1.5g
 *     现值:     HIGH=1.8g / LOW=1.5g
 *
 *   第一版曾把两者一起抬到 5.0/4.5 —— 那是为了迁就"被放大 4 倍的读数"
 *   (静止 |a| 显示 3.9): 3.9 > 2.5 会让状态机常年卡在 IMPACT, 而 3.9 永不
 *   < 1.5 又让条件3 永不成立。抬阈值只是让判据在【错误的读数体系】里能跑。
 *
 *   第二版改为在 mpu6050.c 里做【静止自标定】, 用"静止时 |a| ≡ 1g"这条物理
 *   定律反推出真实灵敏度(实测为 ±2g 档), 读数已回到真实 g —— 静止显示 1.0。
 *   读数一修对, 阈值就必须回到真实量纲, 否则 5.0 在新体系里等于"真实 5g
 *   冲击才报警", 比需求还钝一倍。
 *
 *   LOW 保持需求原值 1.5: 静止 |a|=1.0 恒小于它, 本来就成立, 无需改动。
 *
 *   HIGH 只能取 1.8, 这是硬件的物理上限而非取舍: 芯片实际量程 ±2g, 冲击
 *   超过 2.0g 即被削顶, 若仍用需求的 2.5 则 2.0 < 2.5 → 条件1 物理上永不
 *   成立。1.8 < 2.0 才留出可触发的余量。
 *   换到能真正换挡 ±8g 的芯片后, 把 HIGH 改回 2.5f 即可完全回到需求设计。
 *   完整推导见 docs/26-加速度静止自标定.md。
 *
 * ⚠ 状态机必须有对外可见的输出: 排查时不要靠读代码猜它停在哪一步。
 *   本版已把状态显示到 OLED(Display_Task 第 6 行: FF/IMP/CFM 三个瞬时态),
 *   配合 FallDetect_GetPeak() 的峰值, "有没有采到撞击 / 判据推进到哪一步"
 *   都能一眼看到, 不必再靠"扔一次试试"。
 *
 * 状态迁移(两条入口, 汇合到同一确认流程):
 *   IDLE --条件1--> IMPACT --条件2--> CONFIRM --条件3--> 报警 + LOCKOUT
 *                               \--窗口超时--> IDLE
 *   IDLE --持续失重--> FREEFALL --落地(失重结束)--> CONFIRM --条件3--> 报警
 *                                \--超时未落地--> IDLE
 *   CONFIRM --稳定带之外(回弹/晃动/又掉下去)--> 只重置稳定计时, 仍留在 CONFIRM
 *   CONFIRM --超时(3×STABLE_MS)仍不稳--> IDLE
 *   触发后进入 LOCKOUT(FALL_LOCKOUT_MS), 期间不再重复报警(防抖/防轰炸)。
 *
 * 两条入口何时都不成立: 见 user_config.h 第五节末尾的说明。
 *
 * ⚠ 采样率与判据窗口的关系(2026-09-16 修订, 这条曾经是真正的病根):
 *   旧版把本函数挂在 Sensor_Task 上(周期 100ms ⇒ 10Hz), 于是:
 *     · 撞击只持续 5~20ms, 落在两次采样之间的概率 >80%, 信号根本没被看到;
 *     · 条件2 要求"100ms 内再次超阈", 而采样周期就等于窗口宽度 ——
 *       要满足它等于要求撞击持续 ≥100ms, 真实撞击远达不到。
 *   ⇒ 现在本函数改由【撞击监视任务】以 IMPACT_PERIOD_MS(5ms / 200Hz) 驱动,
 *     MPU 的 ODR 提到 1kHz、DLPF 放宽到 188Hz, 撞击尖峰才第一次真正被看见。
 *   教训: 排查"检测不触发"时, 先确认"信号被采到了没有", 再怀疑阈值。
 *
 * ⚠ 两条触发路径(2026-09-16 新增第二条):
 *   路径A(需求原判据): |a|>HIGH → 100ms 内再次 >HIGH → 稳定 → 报警
 *   路径B(自由落体):   |a|<FALL_FREEFALL_G 持续够久 → 失重结束 → 稳定 → 报警
 *
 *   为什么必须补路径B: 落到软垫/地毯上时冲击被缓冲, 常常只有【一次】尖峰,
 *   不产生二次碰撞 ⇒ 路径A 不成立 ⇒ 掉下去也不报警。而"先失重、后落地"
 *   才是"掉下去"最本质的特征, 且 0g 距离 ±2g 削顶边界最远, 最不受量程限制。
 *   两条路径汇合到同一个 CONFIRM→稳定流程, 所以"走路磕门框"(有撞击无失重)
 *   与拿到手上把玩(无失重)都不会误报。
 *
 * ⚠ 路径B 的"落地"必须用 FALL_FREEFALL_LAND_G(0.9g), 不能用 HIGH_G(1.8g):
 *   这是本版修掉的第二个真 bug。用 1.8g 时, 路径B 仍然卡在它本该绕开的采样
 *   竞态上 —— 撞击脉冲高于 1.8g 的时间只有 1~3ms, 主机 5ms 采一次, 数值仿真
 *   扫 40 个相位只有 20 次命中(50%)。而"持续失重"一旦确认, 要问的只是
 *   "失重结束没有"; 0g 与 1.0g 差着一个 g, 过渡又宽又慢, 0.9g 必然跨得到,
 *   命中率 100%。详见 user_config.h 的 FALL_FREEFALL_LAND_G 注释.
 * ========================================================================== */

/* 峰值保持时长: 超过这么久没有新的更高值, 就退回到当前值。
 * 取 3 秒 —— 比一次摔倒的完整过程(失重+撞击+躺稳约 2 秒)略长, 这样
 * 摔完之后屏幕上还留着撞击峰值, 来得及抄读; 又不会永远停在历史最高值上. */
#define FALL_PEAK_HOLD_MS     3000

typedef enum
{
    FALL_IDLE = 0,
    FALL_FREEFALL,      /* 已确认失重, 正在等落地(路径B) */
    FALL_IMPACT,
    FALL_CONFIRM,
    FALL_LOCKOUT
} FallState_t;

void        FallDetect_Init(void);
/* 每来一个加速度样本调用一次。
 * 返回 1 表示本样本时刻判定为摔倒。
 * ⚠ 必须由高速任务(200Hz 级)调用, 挂在 100ms 的慢任务上等于没接。 */
uint8_t     FallDetect_Update(float ax, float ay, float az, uint32_t now_ms);
FallState_t FallDetect_GetState(void);
float       FallDetect_GetMagnitude(void);

/* 最近 PEAK_HOLD_MS 内的 |a| 峰值 —— 现场判断"撞击到底有没有被采到"的
 * 唯一凭据: 显示 2.0 说明芯片看到了撞击(量程内被削顶), 一直 1.0 则说明
 * 根本没采到, 该查采样率/带宽, 而不是继续调阈值。 */
float       FallDetect_GetPeak(void);

#endif /* __FALL_DETECT_H */
