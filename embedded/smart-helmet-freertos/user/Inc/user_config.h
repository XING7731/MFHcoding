/* ---- 接触判定与"贴手后稳定期"(2026-09-17 新增) ----
 * 起因: 用户报"心率和血氧测量还是会误测"。前面几版把所有已知的算法缺陷都
 * 补上了(见 docs/29), 但"贴上去的那一瞬间"仍然是误测的高发区, 而它和算法
 * 对不对无关 —— 是物理过程本身没稳定:
 *   ① 直流估计要从"环境光量级"跳到"手指反射光量级"。就算初值取对了,
 *      高通滤波器面对这个阶跃也会先冲出一个远大于脉搏波的尖峰, 被当成搏动;
 *   ② 指尖被压住的前一两秒, 静脉血被挤走、毛细血管血容量重新分布, PPG 的
 *      交流幅度本身在漂 —— 这段时间数出来的 IBI 都不是"心跳间隔";
 *   ③ 手指还在找位置, 微动造成的运动伪影最大。
 * 这三条都不是靠调阈值能解决的, 只能靠"等它稳"。
 *
 * 做法(2026-09-17 二次修订 —— 改成"一次测量"):
 *   贴上手指 → 等 PPG_SETTLE_MS 稳定 → 采集 PPG_MEASURE_MS → 出【最终结果】。
 *
 *     状态        时长      屏上(行0)              上行 hr/spo2
 *     IDLE        ——        put finger on          null
 *     SETTLING    3s         settling in 3..1s      null
 *     MEASURING   10s        pending 10..1s         null      <- 用户要求显示 pending
 *     DONE        ——         done (或 no pulse)     最终值
 *
 * 【为什么稳定期里算法要"照常运行"而不是"停 3 秒再开始"】
 *   如果稳定期里什么都不算, 3 秒后滤波器才从零开始, 又要再等 4 秒窗口填满
 *   + 3 拍 IBI 才出得了数, 用户实际要等 7 秒以上。让算法在稳定期里同时预热,
 *   3 秒一到就已经在正常寻峰了, 采集窗口的第一拍就能用。
 *
 * 判据用【IR 原始值】而不是滤波后的直流: 原始值没有延迟, 手指一盖上立刻
 * 越界。滤波后的直流要经过高通时间常数(0.5Hz ⇒ 约 0.3s)才跟上来。
 * 阈值 2000 的依据: 手指盖住光学窗口时 IR 原始值通常几万, 拿开时只剩
 * 环境光泄漏(几百)。差一个数量级以上, 取中间的 2000 很稳。 */
#define PPG_CONTACT_RAW_TH    2000.0f /* IR 原始值下限: 高于它才认为有手指 */
#define PPG_CONTACT_ON_MS     300     /* 连续这么久都是"有手指"才确认贴上(去抖) */
#define PPG_CONTACT_OFF_MS    800     /* 连续这么久都是"没手指"才确认拿开 */
#define PPG_SETTLE_MS         3000    /* 贴上后先稳定 3 秒(期间只预热, 不采集) */

/* ---- 采集窗口: 用 10 秒的数据算一次, 出最终结果(2026-09-17 新增) ----
 *
 * 【为什么要从"持续测量"改成"一次测量"】
 *   持续测量时屏上的数每 2 秒变一次(其实每拍都在重算), 用户没法判断
 *   "这个数是不是已经稳了"。改成有限窗口后: 10 秒里算法照常积累, 窗口
 *   结束才用【整段数据的中位数】给出一个值, 之后不再变化 ——
 *   用户看到的是一次明确的结果, 而不是一个一直在跳的数。
 *
 * 【为什么是 10 秒】
 *   10 秒在 60~100bpm 下能拿到 10~16 个 IBI, 中位数已经很稳; 再短(3~5 秒)
 *   只有三四拍, 一次假峰就能把中位数带偏。30bpm 的极端下限也有 5 拍可用。
 *
 * 【窗口内累计什么】
 *   IBI(每两拍之间的间隔)与 R(血氧比值)各存一份, 都是【每拍一个样本】,
 *   结束时各自取中位数。中位数天然抗单点异常 —— 这就是"一次测量"相比
 *   "滑动平均"的好处: 不需要额外的滤波器, 也不会被一次伪影拖走。
 *
 * PPG_WIN_MAX = 40: 15 秒窗口(2026-09-22 从 10 秒改来) @ 150bpm
 *   (不应期下限 400ms)最多 37 拍 —— 40 刚好留 3 拍余量。
 *   ⚠ 这个上限是【按 15000ms / PPG_HR_MIN_IBI_MS 算出来的】: 以后谁再动
 *     PPG_MEASURE_MS 或不应期, 都要回来核对它, 否则窗口尾部攒到的拍会被
 *     静默丢掉(丢的不报错, 只让"拍数不够"的失败变多)。
 * PPG_WIN_IBI_MIN / PPG_WIN_R_MIN: 少于这么多样本就不给结果 ——
 *   宁可报"没测到", 也不要拿 1~2 拍算一个看起来很正常的数出来。
 *
 * 【PPG_WIN_IBI_CONSIST_PCT: 一致占比门槛 —— 这条是仿真查出来的, 不是设计出来的】
 *   中位数能挡住少数离群点, 但挡不住【系统性双峰】: 信号弱(调制比 0.3%)而基线
 *   漂移比脉搏波还大时, 一个心搏会被顶出两个局部极大值, 检出的间隔就变成
 *   "500, 1000, 500, 1000..." —— 而中位数正好落在两峰【之间】, 给不出明显的
 *   错值。tools/ppg_measure_sim.py 实测(真值 72bpm, 6 个噪声 realization):
 *     不设门槛: 6 次里有 2 次报出 115 / 130 bpm —— 用户看到的就是"读数随机";
 *     设门槛后: 一次偏差 > 5 的都没有, 不能确定的 3 次明确报"没测到"。
 *   判据: 与中位数相差不超过 PPG_IBI_TOL_PCT 的拍数, 要占总拍数的这个百分比
 *   以上, 并且本身不少于 PPG_WIN_IBI_MIN 拍。
 *   取 70: 干净信号实测一致占比 100%(四个心率都是), 上例中被打掉的两次是
 *   0% 和 67% —— 门槛放在 70 既不会误伤正常信号, 又能挡住双峰。
 *   【一句话】不知道就说不确定, 比给一个看起来很正常的错数强。 */
/* 采集窗口长度。
 *
 * 【2026-09-22: 10 秒 → 15 秒。依据是 tools/ppg_retry_sim.py, 不是感觉】
 *   条件取 ppg_yield_sweep.py 第十二节那一组(幅度 305 = 实测 a 档, OU 漂移
 *   std=600 tau=0.8s), 同一组换漂移形态复核一遍:
 *     窗口      不平滑 OU(出数/错值/无结果)   带限 OU
 *     10 秒     29% / 50% / 21%              62% / 29% /  8%
 *     15 秒     42% / 33% / 25%              79% / 21% /  0%
 *     20 秒     42% / 42% / 17%              83% / 17% /  0%
 *   两种漂移实现【同方向】, 所以这条经得起复核(对照 12-G 的教训):
 *   10→15 秒收益明显(+13 / +17 个百分点), 15→20 秒收益小且代价高
 *   (等待 +33%; 不平滑那一组错值率还从 33% 涨回 42%)。⇒ 取 15 秒。
 *
 * 【同一轮仿真否掉了三个"看起来能提高成功率"的改法, 一并记下来】
 *   ① 自适应窗口(攒够 6~8 拍就提前收工): 更差, 不是更好 ——
 *      平均只等 12.9~14.4 秒, 出数率反而掉到 29%(固定 15 秒是 42%)。
 *      原因: 拍数越多, 中位数越稳、"一致占比"越难被双峰伪造; 早退等于用
 *      "刚好过门槛的 6 拍"去定结果。这条最反直觉, 所以两种漂移都测了。
 *   ② 自动重试(失败就自动重开一个窗口): 几乎没用 ——
 *      不平滑 42%→46%(2 次)→50%(3 次); 带限 79%→79%→79%(完全不变)。
 *      机制: 带限那组本来就没有"无结果", 而重试只能把"无结果"变成结果,
 *      它没法把已经被判据否掉的错值救回来。代价是最长等待翻倍。
 *   ③ 低置信兜底(所有尝试都没过高置信门槛时, 仍把中位数报出来):
 *      数据说【不能开】。不合格的那些窗口里, 报出来的值落在 ±5bpm 内的比例
 *      只有 17%(口径 a)和 0%(口径 b) —— 也就是说门槛挡的正是系统性双峰,
 *      放开就是拿错值换读数。这条与"宁可说不知道"的原则一致。
 *   (判据 b = 保留"至少 3 拍互相一致", 只放弃 70% 占比 —— 它比 a 更严,
 *    给对率却更低, 说明问题不在"占比"而在"这些拍本身就不可信"。) */
#define PPG_MEASURE_MS        15000   /* 采集窗口长度 */
#define PPG_WIN_MAX           40      /* 窗口内最多累计的拍数(IBI 与 R 共用上限) */
