/* ========================= 一、引脚分配 =========================
 * 分配原则: 复用已有的 USART1(ESP01S)/USART2(调试)/PA1(DHT11),
 *           I2C1 三器件共总线, 其余按不冲突原则分配。
 * -----------------------------------------------------------------
 *  PA1   DHT11 DATA          (单总线, 需 4.7K~10K 上拉)
 *  PB12  DS18B20 DQ          (1-Wire, 开漏 + 4.7K 上拉)
 *  PA4   SOS 按键            (下降沿 EXTI4, 按键另一端接 GND)
 *  PB5   蜂鸣器驱动          (推挽输出)
 *  PB1   MQ-2 模拟输出        (ADC1_IN9)   ← ADC1 唯一通道
 *  (PB0 原为 PT0603 光照模拟输出 ADC1_IN8, 2026-09-22 随光照功能删除, 见 docs/39)
 *  PB6   I2C1 SCL  → OLED(0x3C) / MAX30102(0x57)  [+ MPU6050, 见 MPU6050_ON_I2C2]
 *  PB7   I2C1 SDA
 *  PB10  I2C2 SCL  → MPU6050(0x68)  ← 仅当 MPU6050_ON_I2C2 = 1 时使用
 *  PB11  I2C2 SDA
 *  PA9   USART1 TX → ESP01S RX
 *  PA10  USART1 RX ← ESP01S TX
 *  PA2   USART2 TX → 调试串口
 *  PA3   USART2 RX
 *  PA13/PA14  SWD 调试 (不可占用)
 * ================================================================= */

/* ============ 一之二、姿态传感器(MPU6050)挂在哪条 I2C 总线 ============
 * 【先纠正一个常见误解: 三个器件共用一对引脚并不是错误】
 *   I2C 是"总线", OLED(0x3C) / MPU6050(0x68) / MAX30102(0x57) 并联在
 *   PB6+PB7 上、靠从机地址区分, 主机"点名"通信, 未被点名的器件保持沉默 ——
 *   这是 I2C 的正常用法, 不需要片选线。共用状态下三个器件都能正常工作。
 *
 * 【那什么情况下值得把 MPU6050 单独分出去】
 *   ① 抗"单器件拖死总线": 若某个器件故障把 SDA 拉死在低电平, 整条总线会
 *      一起瘫痪, 现象是"连 OLED 也黑屏", 看起来极像引脚打架, 实际是单器件
 *      拖死整条线。分开之后, MPU6050 挂死不会再连累屏幕和心率;
 *   ② 想在逻辑分析仪上单独盯姿态数据流, 不被 OLED 刷新(500ms 一次整屏写)干扰;
 *   ③ 结构上 MPU6050 装在帽子顶、离主板较远, 与屏幕走线分开更省事。
 *   若以上都不成立, 保持 0(共用)即可 —— 共用完全能满足功能要求。
 *
 * 【改到 I2C2 要做两件事, 缺一不可】
 *   硬件: 把 MPU6050 的 SCL 从 PB6 改接 PB10, SDA 从 PB7 改接 PB11。
 *         3.3V / GND 不变, INT 仍悬空(固件轮询), AD0 仍接 GND(保持 0x68)。
 *         I2C2 这条线上仍需一组 4.7K 上拉到 3.3V; GY-521 类模块板载自带,
 *         不要再叠加。
 *   软件: 把下面这行改成 1, 重新编译烧录。
 *   上电自检屏会分别列出两条总线扫到的地址和各自对应的引脚, 接错一眼可见
 *   (见 main.c 的 I2C_BusScan / I2C_ScanShowOnOled)。
 *
 * 【为什么是 PB10/PB11】
 *   STM32F103C8T6 只有两个硬件 I2C:
 *       I2C1 → PB6/PB7 (可用 AFIO 重映射到 PB8/PB9)
 *       I2C2 → PB10/PB11 (无重映射选项)
 *   I2C1 上已经挂着 OLED 和 MAX30102, 若把 I2C1 重映射到 PB8/PB9, 等于把
 *   这两个器件也一起搬走, 所以让 MPU6050 改用 I2C2 最省事。PB10/PB11 在
 *   上面的引脚分配里本来就是空闲的。
 *
 * 【两个细节, 避免误判】
 *   - 置 1 后若自检屏显示 "I2C2: none" 且 M:--, 说明线还没换到 PB10/PB11
 *     (固件没问题, 是接线还停在旧脚位);
 *   - 置 0 时完全不初始化 I2C2, PB10/PB11 保持空闲, 不占用。 */
