/* ===================== 十、阈值在线配置(小程序下发) =====================
 *
 * 【要解决的问题】
 *   门限全是编译期宏时, "现在就想把高温门限从 40℃ 调到 25℃"这件事必须重新
 *   编译烧录。而演示现场恰恰需要它: 环境只有 26℃, 40℃ 的高温报警永远演示
 *   不出来。做成在线可配之后, 小程序里拖一下滑块, 帽子上的蜂鸣器立刻按新的
 *   门限工作。
 *
 * 【消息怎么走到设备 —— 一次下行经过的四段路】
 *   ① 小程序 → HTTPS  apis.bemfa.com/va/sendMessage?uid=&topic=<主题>/set
 *                &type=1&msg=<报文>       (只需 request 合法域名, 见小程序 README)
 *   ② 巴法云 → 把消息发布到 "<主题>/set"。按官方文档, 这个后缀表示
 *      "推送给所有订阅了 <主题> 的设备"。
 *   ③ 设备 → 上报时已经订阅了 <主题>(见上面 MQTT_SUBSCRIBE_ENABLE),
 *      所以这条消息会被回推给设备, 落在 ESP01S 的 AT 接收缓冲里。
 *   ④ 固件 → WifiTask 每轮(10 秒)扫一次接收缓冲, 认出 "cfg":1 标记就交给
 *      AlarmCfg_ApplyJson 解析(见 app_tasks.c 的 net_poll_config)。
 *   设备侧没有新增连接、没有新增订阅、没有新增主题 —— 用的就是现成的那条路。
 *
 * 【报文格式(必须一字不差)】
 *   {"cfg":1,"m":7,"tHi":25,"tLo":10,"hHi":80,"hLo":20,"gas":50,
 *    "hrLo":50,"hrHi":120,"sp":90,"buz":1}
 *
 *   键   含义                    量纲/写法        省略时
 *   ------------------------------------------------------------------
 *   cfg  配置标记(必须为 1)     整数            不可省略(靠它认报文)
 *   m    小程序自己的消息序号    整数            可省略, 设备只打日志
 *   tHi  高温门限                ℃, 支持 25.5   保持当前值
 *   tLo  低温门限                ℃              保持当前值
 *   hHi  高湿门限                %RH            保持当前值
 *   hLo  低湿门限                %RH            保持当前值
 *   gas  气体门限(相对量程)      0~100 整数      保持当前值
 *   hrLo 心率下限                bpm 整数        保持当前值
 *   hrHi 心率上限                bpm 整数        保持当前值
 *   sp   血氧下限                % 整数          保持当前值
 *   buz  阈值报警蜂鸣开关         0/1             保持当前值
 *
 *   ★ 温湿度是【×10 定点】写法(25.5 → 255), 而 gas/hrLo/hrHi/sp/buz 是
 *     【纯整数】。这两类在固件里用的是两个不同的解析函数 —— 混用会把
 *     gas=30 读成 300 从而每次都被量程拒掉(tools/alarm_cfg_sim.py 里
 *     有专门的断言锁住这条)。
 *   ★ 字段名不要用 "seq": 设备用它做回环确认("seq":N, 是"自己刚发的报文
 *     有没有经过 Broker"的判据), 下发报文里混进同名字段会污染那个判据。
 *
 * 【为什么报文必须带 "cfg":1 这个标记】
 *   接收缓冲里同时混着 AT 应答、CONNACK/SUBACK、以及设备自己上报的回环
 *   报文。没有标记就无法区分"这是给我的配置"还是"这是我刚发出去的数据"。
 *
 * 【校验: 越界一律【整条】拒绝, 保持原配置】
 *   量程与顺序约束见 alarm_cfg.h(CFG_TEMP_MIN_X10 等)。特别地, 高门限必须
 *   严格大于低门限 —— 否则那条判据会变成"永远为真"或"永远为假"。
 *   小程序侧复制了同一套边界, 目的是让它在【下发前】就拦住自己知道会被拒的
 *   值, 而不是让用户对着"点了没反应"发呆。两侧数值由
 *   tools/alarm_cfg_sim.py 与 tools/wxmp_thresh_test.js 交叉核对。
 *
 * 【生效范围: 只在本机 RAM 里, 掉电回默认】
 *   不写 Flash 的理由见 alarm_cfg.h: 擦一页要停总线 20~40ms, 会把 5ms 周期
 *   的撞击监视任务打断 —— 那是摔倒判据的采样源, 不值得为"门限掉电保存"
 *   冒漏报的风险。
 *   补偿: 上报报文里带 cv(门限指纹), 小程序拿它比对"我下发的那套生效了没有",
 *   不一致就提示重发。也就是把"设备要记住"换成"设备随时可被纠正"。
 *
 * 【演示用法(最实用的一条)】
 *   现场环境 26℃ 想演示高温报警: 在小程序里把"高温门限"拉到 25.0(量程允许
 *   低到 -20), 点下发 → 设备下一轮(≤10 秒)就用新门限判断 → 蜂鸣器按
 *   1.5 秒/次鸣响, 屏上行0 显示 TEMP HIGH, 小程序首页出现预警横幅。
 *   演示完点"恢复默认"即可, 或直接断电重启(门限回到本文件的出厂值)。
 * ====================================================================== */

