/* ---------------- 静默期在线标定开关(2026-09-16 新增) ----------------
 * 【它解决的是"上电自标定没做成"这件事】
 *   上电自标定要求"上电那一瞬间帽子是静止的"。现场几乎不可能每次满足 ——
 *   更常见的是顺手拿在手里就上电了(用户实测反馈:"无论怎么放都还是 3.9",
 *   正是这个原因)。此时上电标定失败, 读数继续被放大 4 倍, 摔倒判据静默失效。
 *
 *   在线标定把这件事变成"随时可修": 运行期间只要检测到一段足够平稳的
 *   窗口(极差 ≤ MPU6050_ONLINE_CAL_SPREAD%), 就用该窗口的【原始码值模值
 *   均值】修正灵敏度 —— 不需要重启, 也不需要专门配合, 放稳一两秒自己就好了。
 *
 *   为什么这样是安全的: 用的仍是同一条物理定律(静止时 |a| ≡ 1g), 且要求
 *   ① 窗口内极差足够小(真的没动) ② 结果落在物理可能的档位区间内。
 *   发力时(走路/摔倒/撞击) 极差必然大, 会被自动排除, 不会把撞击当成 1g。
 *
 *   留着重启即可恢复的开关, 置 0 则只保留"上电那一轮"的标定。 */
#define MPU6050_ONLINE_CAL_ENABLE   1
