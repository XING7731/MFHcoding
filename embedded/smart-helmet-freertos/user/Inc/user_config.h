/* ===================== 三之二、联网稳定性策略 =====================
 * 【为什么需要这些参数 —— "连上了却断了又连、连了又断"的两类原因】
 *   ① 把偶发失败当成"断线": ESP01S 一次 CIPSEND 没等到 "SEND OK",
 *      可能只是链路瞬时拥塞, 连接其实还在。若立刻 CIPCLOSE 重连,
 *      就会放大成一次完整的断连-重连, 现场看就是"反复掉线"。
 *      → 对策: NET_PUB_RETRY_MAX 原地重试, 只有确认链路已死才拆连接。
 *   ② 重连太急: 失败后固定 10s 重连且每次都响 5s 蜂鸣, 信号差时会形成
 *      密集的重连-报警循环。
 *      → 对策: 退避重连(NET_RECONNECT_MIN_MS 起, 翻倍到上限) +
 *              连续失败达 NET_ALARM_AFTER_FAILS 次才鸣响。
 * 调试期建议: 先把 NET_ALARM_ON_FAIL 置 0, 从 USART2 日志判断断在哪一层。
 * ================================================================= */
#define NET_PUB_RETRY_MAX       2       /* 一次上报失败后的原地重试次数(0 = 不重试) */
#define NET_PUB_RETRY_DELAY_MS  300     /* 每次重试前的间隔 */

/* ============ 三之三、送达确认(回环) —— 区分"假成功"与"真送达" ============
 * 【要解决的现象】
 *     屏幕显示 "NET: OK", pub 计数一直在涨, 但巴法云控制台上看不到新消息,
 *     time 一栏停在很久以前不动。
 * 【为什么会"假成功"】
 *     AT+CIPSEND 拿到 "SEND OK" 只代表【ESP01S 自己的 TCP 栈收下了这串字节】,
 *     不代表字节已经到达巴法云。下面几种情况都会"本地成功、云端没收到":
 *       ① 链路已被对端关闭, 模块却还没察觉(半开连接);
 *       ② 同一私钥被另一个客户端顶掉(巴法云同 UID 只允许一条连接) ——
 *          用电脑上的 MQTTX / 本工程的 bemfa_check.py / bemfa_device_sim.py
 *          以同一私钥连一次, 板子就会被顶下线, 但板子自己不知道, 仍会
 *          "发送成功"并把 pub 一路加上去;
 *       ③ 报文被中间设备丢弃。
 *     这些情况的共同点是: pub 在涨, 云端却没有任何新数据 —— 光看 pub 永远
 *     分不清是"云端显示问题"还是"根本没送达"。
 * 【靠什么分清 —— 回环确认】
 *     固件订阅的就是上报用的那个裸主题。巴法云会把消息回推给该主题的
 *     所有订阅者, 其中就包括设备自己。所以在报文里带一个自增序号 seq,
 *     发完之后在接收缓冲里找 "seq":N, —— 
 *         找到了  → 这串字节确实经过了 Broker, 是【真送达】(e 计数 +1)
 *         没找到  → 是【假成功】, 云端根本没收到(p 在涨而 e 不涨)
 *     屏幕上 "NET: OK p=x e=y": p = 发送成功次数, e = 回环确认次数。
 *     正常情况下两者应该同步增长; p 涨而 e 恒为 0 = 数据没上去。
 * 【超时/阈值怎么取】
 *   - 巴法云回环通常在 1s 内; 给 4s 已足够宽容(信号差时也只是偶尔漏判一次,
 *     不会造成误重连)。
 *   - 连续 NET_ECHO_FAIL_MAX 次"发布成功但无回环"就判定这条连接是死的,
 *     主动断开重连 —— 这正是"被别的客户端顶掉"之后的自愈动作。
 * 【什么时候可以关掉】
 *   纯粹想省掉这 4s 等待时置 0。关掉后 OLED 只显示 p 不显示 e,
 *   也就重新失去"真假成功"的判别能力。 */
#define NET_ECHO_CONFIRM_ENABLE 1       /* 1 = 发布后等待云端回环确认 */
#define NET_ECHO_TIMEOUT_MS     4000    /* 单次等待回环的超时(ms) */
#define NET_ECHO_FAIL_MAX       3       /* 连续多次无回环即判链路已死, 强制重连 */
#define NET_RECONNECT_MIN_MS    5000    /* 重连退避起点 */
#define NET_RECONNECT_MAX_MS    60000   /* 重连退避上限(封顶, 不再翻倍) */
#define NET_ALARM_AFTER_FAILS   3       /* 连续失败达到此次数才触发蜂鸣报警 */

/* ===================== 二之四、上报报文长度上限(重要) =====================
 * 【为什么必须限制长度 —— 实测结论, 不是猜测】
 *   巴法云该主题的"最后一条消息"记录字段只有 191 字节(实测 2026-09-14:
 *   191 字节能被写入, 192 字节开始就写不进去)。超过上限时:
 *       ★ MQTT 转发【照常进行】—— 订阅者能收到完整报文, 设备侧的回环确认
 *         也会成功(e 正常增长), 一切看起来都是好的;
 *       ★ 但这条消息【不会被写进主题记录】—— 控制台/HTTP 接口的
 *         msg/time 永远停在更早的那一条上。
 *   于是就出现了最难查的那种现象: 设备显示发送成功、订阅者确实收得到,
 *   唯独控制台"没有数据"。
 *
 *   所以: 上报报文必须压到 NET_PAYLOAD_MAX 以内(超出时由 build_data_json()
 *   先做一次"有内容"的降级: 丢温湿度/气体, 保住报警与诊断字段;
 *   再由 enforce_payload_limit() 兜底成最小报文 —— 详见 app_tasks.c)。
 *   NET_JSON_COMPACT = 1 时使用紧凑键名, 典型报文约 165 字节。
 *
 * 【字段映射(紧凑 → 原义)】  (2026-09-22 更新, 见 docs/37 与 docs/39)
 *   seq=序号            hr=心率(bpm)     spo2=血氧(%)     sc=血氧是否已标定
 *   ps=PPG测量状态      cv=当前生效门限的指纹(见第十节)
 *   d=红外直流(不钳位)  a=脉搏波峰值幅度 b=窗口内合格 IBI 拍数
 *   t=温度(℃)           h=湿度(%)       gas=气体 ADC
 *   ax/ay/az=三轴加速度 st=状态         up=运行毫秒数
 *
 *   ---- 2026-09-22 起不再上报的三个 ----
 *   ts (设备本地时间 HH:MM:SS) 与 tsv (该校时标记):
 *     板子无 VBAT 电池, RTC 上电即回编译初值, 这个时间本来就不可信;
 *     而 d/a/b 是"心率测不出"时唯一能把病因分开的三个量, 长度必须腾给它。
 *   lux (光照 ADC 原始值): 用户要求彻底移除光照功能, 见 docs/39。
 *
 * 【什么时候可以改回完整报文】
 *   只在【本机/局域网上位机】消费数据、不在乎巴法云控制台能否显示时,
 *   把 NET_JSON_COMPACT 置 0 即可恢复完整字段(约 250 字节, 云控制台看不到)。 */
#define NET_JSON_COMPACT      1     /* 1 = 紧凑键名(≈165B, 能被云端记录) */
#define NET_PAYLOAD_MAX       180   /* 报文长度硬上限, 超出则降级(见 app_tasks.c) */

