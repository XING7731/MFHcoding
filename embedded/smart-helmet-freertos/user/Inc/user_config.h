#define PPG_HR_MAX_IBI_MS     2000  /* 对应下限 30bpm */

/* ---- 重搏切迹抑制(2026-09-17 新增) ----
 * 起因: 用户实测报"pending 10s 正常倒数完, 10 秒后仍是 HR:-- SpO2:--,
 *       行0 显示 no pulse, retry"。硬件/接线/器件都在线(能走到 pending)。
 *
 * 数值复现(tools/ppg_nopulse_sim.py)把三个候选原因逐个放进仿真, 只有第三个
 * 能复现出"零拍/错值":
 *   W1  峰值参考被稳定期的运动伪影顶高   → 否。4Hz 低通把 150ms 的短脉冲
 *        削掉一半以上: 8000 LSB 的脉冲只把参考从 577 抬到 824;
 *        2.5Hz 持续晃动(幅度 4000, 6.7 倍于脉搏波)也只到 580。
 *   W2  采集期的周期性伪影(手指摩擦)      → 否。同样够不到峰值参考。
 *   W3  重搏切迹被当成第二次搏动          → 是, 确定性复现。
 *
 * W3 的机制: 基线波形 sin(φ)+0.35sin(2φ+0.6) 是平滑的、每拍只有一个极大值,
 * 所以"改完之前那 30 项断言全过"根本不能说明实物上寻峰不会被骗。真实 PPG
 * 有重搏波时, 一个心搏被数成两拍, 窗口内的 IBI 变成"840, 300, 520..." ——
 * 一旦前 3 拍里混进 300/520, 中位数就锁死在半拍间隔上, 之后每一次【真搏动】
 * 反而成了离群值; 连续 PPG_IBI_RESET_STREAK 次对不上就清空重来, 整个 10 秒
 * 窗口在"3 拍 → 清空 → 3 拍"之间循环, 屏上永远是 no pulse, retry。
 * 实测(72bpm): 切迹 40% 时窗口只攒到 3 拍; 切迹 55% 时更糟 ——
 * 50bpm 不报"没测到", 而是报出 71bpm(+21)的错值。
 *
 * 两条修法(见 heart_rate.c 的 on_peak):
 *   ① 不应期 300→400ms: 粗筛, 把 300ms 附近的切迹直接关在门外;
 *   ② 切迹抑制(下面这三个参数): 细筛, 用【已接受的 IBI 中位数】当参照,
 *      间隔短于它 PPG_NOTCH_MIN_RATIO 就不算一拍。
 *      为什么用【时间】而不是幅度: 幅度型判据(峰后必须回落到某条线)对基线
 *      漂移敏感 —— 弱信号下漂移(实测 400)比脉搏波(150)还大, 波形谷底被抬高,
 *      该判据会漏拍, 实测把 90bpm 读成 30bpm。IBI 是纯时间量, 与漂移无关。
 *      为什么是 0.60: 本项目关心的 50~120bpm 对应 IBI 500~1200ms,
 *      0.60×500 = 300ms(刚好挡住切迹), 0.60×1200 = 720ms < 1200ms
 *      (真搏动一律放行), 两头都留得住。
 *      【演化说明】最初用"窗口内 IBI 的上界(max)"当参照, 后来改成【最近 5 拍
 *      的滚动中位数】: 上界一旦被一次异常大的间隔(如 1640ms)抬高, 会把后面
 *      所有真间隔(1000ms 被判成"太短")全部拒掉, 且无法自愈; 滚动中位数会
 *      随新样本自己降回来。 */
#define PPG_NOTCH_MIN_RATIO   0.60f  /* 间隔 < 该比例 × 已有 IBI 中位数 → 不算一拍 */
#define PPG_NOTCH_EST_BEATS   5      /* 滚动参照用的最近拍数 */
#define PPG_NOTCH_EST_MIN     3      /* 至少攒到这么多拍才启用(前 2 拍无参照) */

